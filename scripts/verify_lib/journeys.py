from collections.abc import Mapping
from pathlib import Path

from verify_lib.core import (
    GIT_HOOKS,
    HTTPS,
    IDENTITY,
    MESSAGE,
    MESSAGE_HOOK,
    PRIVATE_MODE,
    SETUP_HOOK_COMMAND,
    STAGED_HOOK,
    Run,
    blocked,
    exited,
    git_commit,
    hook_passed,
    remove_markers,
    require,
    signed,
)

CANARY = "verify-canary-private-name"
NAMED_FILE = f"{CANARY}-notes.txt"
ZERO = "0" * 40
# No privacy rule matches a Slack token, so only Gitleaks can block this message.
SLACK_TOKEN = "xoxb-" + "1234567890123-1234567890123-" + "AbCdEfGhIjKlMnOpQrStUvWx"
MESSAGE_SECRET = f'- slack = "{SLACK_TOKEN}"\n'
# A line Git removes, with all below it, only for `git commit -v` or cleanup=scissors.
SCISSORS = "# ------------------------ >8 ------------------------\n"
# Split, so this source holds no home path; Git writes it whole in a comment line.
COMMENT_BRANCH = "verify/" + "home/someone"
COMMIT_FORMS: tuple[tuple[str, ...], ...] = (("-a",), ("--", "README.md"))
SETUP_DRIVER = Path(__file__).with_name("setup_driver.py")


def _driver(
    run: Run, project: Path, *, preflight: bool, transport: str, mode: str
) -> list[str | Path]:
    if not preflight and run.feature not in run.features_without_preflight:
        run.features_without_preflight.append(run.feature)
    return [
        run.python,
        "-I",
        SETUP_DRIVER,
        run.work / "source/src",
        project,
        run.revision,
        IDENTITY["FIRST_COMMIT_AUTHOR_NAME"],
        IDENTITY["FIRST_COMMIT_AUTHOR_EMAIL"],
        run.environment["VERIFY_KEY"] + ".pub",
        "preflight" if preflight else "skip",
        transport,
        mode,
    ]


def setup_journey(
    run: Run,
    project: Path,
    *,
    preflight: bool,
    transport: str,
    environment: Mapping[str, str] | None = None,
) -> tuple[int, str]:
    return run.command(
        _driver(run, project, preflight=preflight, transport=transport, mode="apply"),
        run.work,
        environment=environment,
    )


def preview_setup(run: Run, project: Path) -> tuple[int, str]:
    return run.command(
        _driver(run, project, preflight=False, transport="https", mode="dry-run"),
        run.work,
    )


def feature_setup(run: Run) -> list[str]:
    project = run.work / "project"
    project.mkdir()
    code, output = setup_journey(run, project, preflight=False, transport="https")
    exited(code, 0, "setup")
    run.project = project
    hook_file = (project / ".pre-commit-config.yaml").read_text("utf-8")
    values = project / ".local/first-commit/private-values.txt"
    ignored, _ = run.command(["git", "check-ignore", "-q", values], project)
    readme = (project / "README.md").read_text("utf-8")
    hooks = [
        project / GIT_HOOKS / stage
        for stage in ("pre-commit", "commit-msg", "pre-push")
    ]
    return [
        require(
            condition="Verification: passed" in output,
            observed="setup printed Verification: passed",
        ),
        require(
            condition=f'repo: "{HTTPS}"' in hook_file
            and f'rev: "{run.revision}"' in hook_file,
            observed="hooks pinned to the HTTPS address and the snapshot commit",
        ),
        require(
            condition="- id: first-commit-setup" in hook_file,
            observed="setup hook listed in .pre-commit-config.yaml",
        ),
        require(
            condition=values.stat().st_mode & 0o777 == PRIVATE_MODE and ignored == 0,
            observed="private-values list is mode 600 and ignored by Git",
        ),
        require(
            condition=(project / ".local/first-commit/contributor.json").is_file(),
            observed="contributor record written",
        ),
        require(
            condition=(project / ".repo-policy.json").is_file(),
            observed=".repo-policy.json written",
        ),
        require(
            condition=all(h.is_file() for h in hooks),
            observed="pre-commit, commit-msg, and pre-push hooks installed",
        ),
        require(
            condition="Generated by first-commit" not in readme,
            observed="starter marker does not name the tool",
        ),
        require(
            condition=SETUP_HOOK_COMMAND in readme,
            observed="starter README names the clone setup command",
        ),
    ]


def feature_commit(run: Run) -> list[str]:
    project = run.project
    remove_markers(project)
    run.command(["git", "add", "-A"], project, expect=0)
    code, output = git_commit(run, project)
    return [
        exited(code, 0, "the first commit"),
        require(
            condition=hook_passed(output, STAGED_HOOK)
            and hook_passed(output, MESSAGE_HOOK),
            observed=f"'{STAGED_HOOK}' and '{MESSAGE_HOOK}' each printed Passed",
        ),
        require(
            condition=signed(run, project),
            observed="the commit carries an SSH signature",
        ),
    ]


def _private_content(run: Run, project: Path) -> list[str]:
    (project / "notes.txt").write_text(f"written by {CANARY}\n", "utf-8")
    run.command(["git", "add", "notes.txt"], project, expect=0)
    code, output = git_commit(run, project)
    run.command(["git", "reset", "-q", "notes.txt"], project)
    printed = output.count(CANARY)
    return [
        blocked(code, "a commit with a planted private value"),
        require(
            condition="privacy.private-literal" in output,
            observed="privacy.private-literal reported",
        ),
        require(
            condition="  fix: Remove the private value" in output,
            observed="fix line printed",
        ),
        require(
            condition=printed == 0,
            observed=f"the private value was never printed (count {printed})",
        ),
    ]


def _private_file_name(run: Run, project: Path) -> list[str]:
    (project / NAMED_FILE).write_text("public text\n", "utf-8")
    run.command(["git", "add", NAMED_FILE], project, expect=0)
    code, output = git_commit(run, project)
    run.command(["git", "reset", "-q", NAMED_FILE], project)
    printed = output.count(CANARY)
    return [
        blocked(code, "a commit of a file named with the private value"),
        require(
            condition='privacy.private-path "<private value>-notes.txt":' in output,
            observed="privacy.private-path reported at the masked path",
        ),
        require(
            condition=printed == 0,
            observed=f"the private value in the name was never printed ({printed})",
        ),
    ]


def feature_privacy(run: Run) -> list[str]:
    project = run.project
    values = project / ".local/first-commit/private-values.txt"
    before = values.read_text("utf-8")
    values.write_text(before + CANARY + "\n", "utf-8")
    try:
        return [*_private_content(run, project), *_private_file_name(run, project)]
    finally:
        for name in ("notes.txt", NAMED_FILE):
            run.command(["git", "reset", "-q", "--", name], project)
            (project / name).unlink(missing_ok=True)
        values.write_text(before, "utf-8")


def feature_message(run: Run) -> list[str]:
    project = run.project
    (project / "message.txt").write_text("one line\n", "utf-8")
    run.command(["git", "add", "message.txt"], project, expect=0)
    bad, bad_output = git_commit(run, project, "did stuff\n")
    leaked, leaked_output = git_commit(run, project, MESSAGE + MESSAGE_SECRET)
    good, _ = git_commit(run, project)
    return [
        blocked(bad, "a commit with the message 'did stuff'"),
        require(
            condition="message.header" in bad_output, observed="message.header reported"
        ),
        require(
            condition="  fix: Start the message with" in bad_output,
            observed="fix line printed",
        ),
        blocked(leaked, "a valid message that holds a Slack token"),
        require(
            condition='secrets.gitleaks "<commit-message>":' in leaked_output,
            observed="secrets.gitleaks reported at <commit-message>",
        ),
        require(
            condition=SLACK_TOKEN not in leaked_output,
            observed="the token was never printed",
        ),
        exited(good, 0, "the same change with a valid message"),
        *_secret_below_scissors(run),
        *_comment_line(run),
    ]


def _secret_below_scissors(run: Run) -> list[str]:
    project = run.project
    _, head = run.command(["git", "rev-parse", "HEAD"], project, expect=0)
    try:
        (project / "message.txt").write_text("two lines\nsecond\n", "utf-8")
        run.command(["git", "add", "message.txt"], project, expect=0)
        code, warned = git_commit(run, project, MESSAGE + SCISSORS + MESSAGE_SECRET)
        _, commit = run.command(["git", "rev-parse", "HEAD"], project, expect=0)
        pushed, output = run.command(
            [project / GIT_HOOKS / "pre-push", "origin", HTTPS],
            project,
            stdin=f"refs/heads/main {commit.strip()} refs/heads/main {ZERO}\n",
        )
        return [
            exited(
                code,
                0,
                "a commit made with -F whose message holds a Slack token below a "
                "hand-written scissors line",
            ),
            require(
                condition="below the scissors line is committed" in warned
                and SLACK_TOKEN not in warned,
                observed="the commit-message hook warned about the text below the "
                "line without printing the token",
            ),
            blocked(pushed, "the pre-push hook for that commit"),
            require(
                condition='secrets.gitleaks "<commit-message>":' in output
                and f"Commit {commit.strip()[:12]}:" in output,
                observed="secrets.gitleaks reported at <commit-message> with the "
                "short commit id",
            ),
            require(
                condition=SLACK_TOKEN not in output,
                observed="the token was never printed",
            ),
        ]
    finally:
        run.command(["git", "reset", "-q", head.strip()], project, expect=0)
        run.command(["git", "checkout", "-q", "--", "message.txt"], project)


def _comment_line(run: Run) -> list[str]:
    project = run.project
    _, branch = run.command(
        ["git", "symbolic-ref", "--short", "HEAD"], project, expect=0
    )
    run.command(["git", "checkout", "-q", "-b", COMMENT_BRANCH], project, expect=0)
    try:
        (project / "message.txt").write_text("three lines\nsecond\nthird\n", "utf-8")
        run.command(["git", "add", "message.txt"], project, expect=0)
        path = run.work / "message.txt"
        path.write_text(MESSAGE, "utf-8")
        code, warned = run.command(
            ["git", "commit", "-q", "-e", "-F", path],
            project,
            environment={**run.environment, "GIT_EDITOR": "true"},
        )
        _, recorded = run.command(["git", "log", "-1", "--format=%B"], project)
        return [
            exited(
                code,
                0,
                f"a commit on branch {COMMENT_BRANCH} through the editor, whose "
                "comment lines name the branch",
            ),
            require(
                condition="privacy.user-home-path" in warned
                and "A comment line is committed unless" in warned,
                observed="the commit-message hook warned about the comment line",
            ),
            require(
                condition=COMMENT_BRANCH not in recorded,
                observed="Git removed the comment lines from the recorded message",
            ),
        ]
    finally:
        run.command(["git", "checkout", "-q", "-f", branch.strip()], project, expect=0)
        run.command(["git", "branch", "-q", "-D", COMMENT_BRANCH], project)


def feature_control_character(run: Run) -> list[str]:
    project = run.project
    path = project / "control.txt"
    path.write_bytes(b"before\x7fafter\n")
    try:
        run.command(["git", "add", "control.txt"], project, expect=0)
        code, output = git_commit(run, project)
        return [
            blocked(code, "a commit of a text file containing DEL (0x7f)"),
            require(
                condition="text.control-character" in output,
                observed="text.control-character reported",
            ),
            require(
                condition="  fix: Delete the control character from this line."
                in output,
                observed="fix line printed",
            ),
        ]
    finally:
        run.command(["git", "reset", "-q", "control.txt"], project)
        path.unlink(missing_ok=True)


def _commit_form(run: Run, project: Path, form: tuple[str, ...]) -> tuple[int, str]:
    path = run.work / "message.txt"
    path.write_text(MESSAGE, "utf-8")
    return run.command(["git", "commit", "-q", "-F", path, *form], project)


def _commit_all_forms(run: Run, project: Path, before: bytes) -> list[str]:
    readme = project / "README.md"
    observed = []
    for form in COMMIT_FORMS:
        shown = " ".join(("git commit", *form))
        readme.write_bytes(before + b"planted\x7fdefect\n")
        code, output = _commit_form(run, project, form)
        observed += [
            blocked(code, f"`{shown}` of README.md with an unstaged DEL (0x7f)"),
            require(
                condition="text.control-character" in output,
                observed=f"`{shown}` reported text.control-character",
            ),
        ]
    for number, form in enumerate(COMMIT_FORMS, 1):
        shown = " ".join(("git commit", *form))
        expected = before + f"Clean change {number}.\n".encode()
        readme.write_bytes(expected)
        code, output = _commit_form(run, project, form)
        committed = run.command(["git", "show", "HEAD:README.md"], project)[1]
        observed += [
            exited(code, 0, f"`{shown}` of README.md with a clean change"),
            require(
                condition=hook_passed(output, STAGED_HOOK),
                observed=f"`{shown}`: the staged hook Passed",
            ),
            require(
                condition=committed.encode() == expected,
                observed=f"`{shown}` committed the expected README.md bytes",
            ),
        ]
    return observed


def feature_commit_all(run: Run) -> list[str]:
    project = run.project
    readme = project / "README.md"
    before = readme.read_bytes()
    _, head = run.command(["git", "rev-parse", "HEAD"], project, expect=0)
    try:
        return _commit_all_forms(run, project, before)
    finally:
        run.command(["git", "reset", "-q", head.strip()], project, expect=0)
        readme.write_bytes(before)
