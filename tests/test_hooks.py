import sys
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

from first_commit.git import GitError
from first_commit.hooks import hook_findings
from tests.support import initialize_repository, run_git


class HooksTest(unittest.TestCase):
    def test_hook_findings_handle_git_metadata_failure(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            initialize_repository(root)
            with patch("first_commit.hooks.run_git", side_effect=GitError("failed")):
                findings = hook_findings(root)

        self.assertEqual(3, len(findings))

    def test_hook_findings_reject_invalid_hook_content(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            initialize_repository(root)
            hooks = Path(
                run_git(root, "rev-parse", "--git-path", "hooks")
                .stdout.decode()
                .strip()
            )
            if not hooks.is_absolute():
                hooks = root / hooks
            for hook_type in ("pre-commit", "commit-msg", "pre-push"):
                (hooks / hook_type).write_text("#!/bin/sh\n", encoding="utf-8")

            findings = hook_findings(root)

        self.assertEqual(3, len(findings))
        self.assertEqual({"hooks.invalid"}, {item.rule_id for item in findings})

    def test_reports_missing_declared_hooks(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            initialize_repository(root)

            findings = hook_findings(root)

        self.assertEqual(
            ["hooks.missing", "hooks.missing", "hooks.missing"],
            [finding.rule_id for finding in findings],
        )

    def test_accepts_executable_pre_commit_hooks(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            initialize_repository(root)
            hooks = Path(
                run_git(root, "rev-parse", "--git-path", "hooks")
                .stdout.decode()
                .strip()
            )
            if not hooks.is_absolute():
                hooks = root / hooks
            for hook_type in ("pre-commit", "commit-msg", "pre-push"):
                path = hooks / hook_type
                path.write_text(
                    "#!/usr/bin/env bash\n# File generated by pre-commit: x\n"
                    f"INSTALL_PYTHON={sys.executable}\n"
                    "ARGS=(hook-impl --config=.pre-commit-config.yaml "
                    f"--hook-type={hook_type})\n",
                    encoding="utf-8",
                )
                path.chmod(0o755)

            findings = hook_findings(root)

        self.assertEqual([], findings)

    def test_a_hook_that_is_not_a_regular_file_is_invalid(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            initialize_repository(root)
            for hook_type in ("pre-commit", "commit-msg", "pre-push"):
                (root / ".git/hooks" / hook_type).mkdir()

            findings = hook_findings(root)

        self.assertEqual(
            ["hooks.invalid"] * 3, [finding.rule_id for finding in findings]
        )

    def test_a_symlinked_hook_is_invalid_even_when_it_points_outside_git(
        self,
    ) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            initialize_repository(root)
            (root / "scripts").mkdir()
            (root / "scripts/hook").write_text("#!/bin/sh\nexit 0\n", "utf-8")
            for hook_type in ("pre-commit", "commit-msg", "pre-push"):
                (root / ".git/hooks" / hook_type).symlink_to("../../scripts/hook")

            findings = hook_findings(root)

        self.assertEqual(
            ["hooks.invalid"] * 3, [finding.rule_id for finding in findings]
        )

    def test_a_symlinked_hook_is_invalid_even_when_it_points_inside_git(
        self,
    ) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            initialize_repository(root)
            for hook_type in ("pre-commit", "commit-msg", "pre-push"):
                target = root / ".git" / f"ready-{hook_type}"
                target.write_text(
                    "#!/usr/bin/env bash\n# File generated by pre-commit: x\n"
                    f"INSTALL_PYTHON={sys.executable}\n"
                    "ARGS=(hook-impl --config=.pre-commit-config.yaml "
                    f"--hook-type={hook_type})\n",
                    encoding="utf-8",
                )
                target.chmod(0o755)
                (root / ".git/hooks" / hook_type).symlink_to(f"../{target.name}")

            findings = hook_findings(root)

        self.assertEqual(
            ["hooks.invalid"] * 3, [finding.rule_id for finding in findings]
        )

    def test_rejects_external_hooks_path_without_reading_hooks(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            base = Path(directory)
            root = base / "repository"
            root.mkdir()
            initialize_repository(root)
            external = base / "hooks"
            external.mkdir()
            run_git(root, "config", "--local", "core.hooksPath", str(external))
            for hook_type in ("pre-commit", "commit-msg", "pre-push"):
                path = external / hook_type
                path.write_text(
                    f"#!/bin/sh\npython -m pre_commit hook-impl --hook-type={hook_type}\n",
                    encoding="utf-8",
                )
                path.chmod(0o755)

            findings = hook_findings(root)

        self.assertEqual(3, len(findings))


if __name__ == "__main__":
    unittest.main()
