HOOK_TYPES = ("pre-commit", "commit-msg", "pre-push")


def generated_hook(hook_type: str, python: str) -> str:
    return (
        "#!/usr/bin/env bash\n# File generated by pre-commit: https://pre-commit.com\n"
        f"INSTALL_PYTHON={python}\n"
        f"ARGS=(hook-impl --config=.pre-commit-config.yaml --hook-type={hook_type})\n"
    )


class HookFileAdoptionTest(SetupFixture):
    def preview(self) -> tuple[str, ...]:
        return setup_repository(
            self.root,
            SetupRequest(revision=REVISION, dry_run=True),
            contributor=self.person,
        )

    def doctor_findings(self) -> list[Finding]:
        policy = parse_policy(b'{"schema_version":1}', self.root)
        with patch("first_commit.validation.validate_scanner"):
            result = validation.doctor(self.root, policy)
        return [item for item in result.findings if item.rule_id == PUSH_CHECK_RULE]

    def test_this_repositorys_own_hook_file_is_accepted_by_setup(self) -> None:
        run_git(self.root, "init", "-q")
        raw = (PROJECT / ".pre-commit-config.yaml").read_bytes()
        (self.root / ".pre-commit-config.yaml").write_bytes(raw)
        check_hook_config(raw, None)
        actions = setup_repository(
            self.root, SetupRequest(dry_run=True), contributor=self.person
        )
        self.assertIn(
            "Hook source: existing project-owned configuration retained", actions
        )
        self.assertIn("Verification: preflight passed; no changes made", actions)
        self.assertEqual([], self.doctor_findings())
        push_hook = raw[raw.index(b"      - id: first-commit-push\n") :]
        push_hook = push_hook[: push_hook.index(b"      - id: project-quality\n")]
        without_push = raw.replace(push_hook, b"")
        with self.assertRaises(HooksMissingError) as error:
            check_hook_config(without_push, None)
        self.assertEqual(("first-commit-push",), error.exception.missing)

    def test_only_a_pre_push_hook_that_runs_the_push_checks_replaces_the_push_hook(
        self,
    ) -> None:
        without_push = hook_bytes(REVISION).replace(
            b"      - id: first-commit-push\n", b""
        )
        cases = (
            ("scripts/gate", "pre-push", "[]", False),
            ("python3 -m pytest", "pre-push", "[]", False),
            ("first-commit check", "pre-commit", "[]", False),
            ("first-commit-check", "pre-push", "[]", False),
            # check only warns about a commit another remote has; the push may pass.
            ("first-commit check", "pre-push", "[]", False),
            ("bin/first-commit check --format json", "pre-push", "[]", False),
            ("first-commit hook pre-push", "pre-push", "[]", True),
            ("bin/first-commit hook pre-push --format json", "pre-push", "[]", True),
            # --root checks another repository, not the one being pushed.
            ("first-commit check --root ../other", "pre-push", "[]", False),
            ("bin/first-commit check --root=../other", "pre-push", "[]", False),
            ("first-commit check", "pre-push", "[--root, ../other]", False),
            ("first-commit hook pre-push", "pre-push", "[--root=../other]", False),
            ("first-commit check", "pre-push", "--root", False),
        )
        for entry, stage, arguments, accepted in cases:
            with self.subTest(entry=entry, stage=stage, arguments=arguments):
                project_hook = (
                    "  - repo: local\n    hooks:\n      - id: project-gate\n"
                    f"        name: gate\n        entry: {entry}\n"
                    f"        language: system\n        always_run: true\n"
                    f"        pass_filenames: false\n        stages: [{stage}]\n"
                    f"        args: {arguments}\n"
                ).encode()
                if accepted:
                    check_hook_config(without_push + project_hook, REVISION)
                    continue
                with self.assertRaises(HooksMissingError) as error:
                    check_hook_config(without_push + project_hook, REVISION)
                self.assertEqual(("first-commit-push",), error.exception.missing)

    def test_doctor_warns_only_when_no_pre_push_hook_runs_first_commit(self) -> None:
        run_git(self.root, "init", "-q")
        self.assertEqual([], self.doctor_findings())
        self.local_hooks()
        self.assertEqual([], self.doctor_findings())
        hook_file = self.root / ".pre-commit-config.yaml"
        hook_file.write_bytes(
            hook_bytes(REVISION).replace(b"      - id: first-commit-push\n", b"")
        )
        self.assertEqual(
            [Severity.WARNING], [item.severity for item in self.doctor_findings()]
        )
        hook_file.write_bytes(b"repos: [\n")
        self.assertEqual(1, len(self.doctor_findings()))
        with patch.dict(sys.modules, {"yaml": None}):
            self.assertEqual([], self.doctor_findings())

    def test_conflicting_settings_name_each_key_and_its_unset_command(self) -> None:
        run_git(self.root, "init", "-q")
        self.local_hooks()
        run_git(self.root, "config", "--local", "user.email", "other@example.com")
        run_git(self.root, "config", "--local", "gpg.format", "openpgp")
        with self.assertRaises(SetupError) as error:
            self.preview()
        message = str(error.exception)
        self.assertIn("user.email", message.splitlines()[0])
        self.assertIn("gpg.format", message.splitlines()[0])
        self.assertNotIn("other@example.com", message)
        for key in ("user.email", "gpg.format"):
            self.assertIn(f"\n  git config --local --unset-all {key}", message)

    def test_a_hooks_path_conflict_names_where_to_unset_it(self) -> None:
        run_git(self.root, "init", "-q")
        self.local_hooks()
        run_git(self.root, "config", "--local", "core.hooksPath", "other")
        with self.assertRaisesRegex(SetupError, "--show-origin core.hooksPath"):
            self.preview()

    def test_setup_and_doctor_share_one_hook_readiness_rule(self) -> None:
        run_git(self.root, "init", "-q")
        self.local_hooks()
        hooks = self.root / ".git/hooks"
        for python, ready in ((sys.executable, True), ("/no/such/python", False)):
            with self.subTest(python=python):
                for hook_type in HOOK_TYPES:
                    path = hooks / hook_type
                    path.write_text(generated_hook(hook_type, python), "utf-8")
                    path.chmod(0o755)
                self.assertEqual(ready, hook_findings(self.root) == [])
                if ready:
                    self.assertIn("Hook scripts: ready", self.preview())
                else:
                    with self.assertRaisesRegex(SetupError, "hook conflicts"):
                        self.preview()
        (hooks / "pre-push").unlink()
        for hook_type in ("pre-commit", "commit-msg"):
            (hooks / hook_type).write_text(
                generated_hook(hook_type, sys.executable), "utf-8"
            )
        self.assertIn("Hook scripts: would install", self.preview())
        self.assertEqual(
            ["hooks.missing"], [item.rule_id for item in hook_findings(self.root)]
        )


class HookProposalTest(CliFixture):
    def setUp(self) -> None:
        super().setUp()
        (self.root / ".gitignore").write_text(".local/\n", "utf-8")
        self.hook_file = self.root / ".pre-commit-config.yaml"
        self.hook_file.write_text(
            "repos:\n  - repo: local\n    hooks:\n      - id: project-lint\n", "utf-8"
        )
        self.git_config = (self.root / ".git/config").read_bytes()

    def test_missing_hooks_get_a_proposal_only_outside_a_dry_run(self) -> None:
        with patch.dict(os.environ, VARIABLES):
            code, _, error = self.run_cli("setup", "--revision", REVISION, "--dry-run")
        self.assertEqual(2, code)
        self.assertIn("first-commit-staged, first-commit-message", error)
        self.assertIn("setup without --dry-run writes the block to merge to", error)
        self.assertFalse((self.root / HOOK_PROPOSAL).exists())

        with patch.dict(os.environ, VARIABLES):
            code, _, error = self.run_cli("setup", "--revision", REVISION, "--yes")
        self.assertEqual(2, code)
        self.assertIn(f"fix: merge {HOOK_PROPOSAL} into .pre-commit-config.yaml", error)
        proposal = (self.root / HOOK_PROPOSAL).read_bytes()
        self.assertTrue(proposal.startswith(PROPOSAL_HEADER.encode("utf-8")))
        header = PROPOSAL_HEADER.encode("utf-8")
        self.assertEqual(hook_bytes(REVISION), proposal.removeprefix(header))
        self.assertEqual(self.git_config, (self.root / ".git/config").read_bytes())
        self.assertFalse((self.root / ".local").exists())
        self.assertFalse(self.identity.exists())

    def test_dry_run_after_the_proposal_exists_gives_the_merge_fix(self) -> None:
        with patch.dict(os.environ, VARIABLES):
            self.run_cli("setup", "--revision", REVISION, "--yes")
            proposal = (self.root / HOOK_PROPOSAL).read_bytes()
            code, _, applied = self.run_cli("setup", "--revision", REVISION, "--yes")
            preview_code, _, preview = self.run_cli(
                "setup", "--revision", REVISION, "--dry-run"
            )
        self.assertEqual((2, 2), (code, preview_code))
        fix = (
            f"fix: merge {HOOK_PROPOSAL} into .pre-commit-config.yaml, delete the "
            "proposal, then rerun setup; setup changed nothing else."
        )
        self.assertIn(fix, applied)
        self.assertIn(fix, preview)
        self.assertEqual(proposal, (self.root / HOOK_PROPOSAL).read_bytes())

    def test_the_hook_proposal_blocks_commits_until_it_is_deleted(self) -> None:
        with patch.dict(os.environ, VARIABLES):
            code, _, _ = self.run_cli("setup", "--revision", REVISION, "--yes")
        self.assertEqual(2, code)
        self.assertTrue(PROPOSAL_HEADER.startswith("# @no-commit\n"))
        policy = parse_policy(b'{"schema_version":1}', self.root)
        with (
            patch("first_commit.validation.scan_staged", return_value=()),
            patch("first_commit.validation.scan_hidden_staged", return_value=()),
        ):
            found = validation.staged(self.root, policy).findings
            self.assertIn(
                (HOOK_PROPOSAL, "scaffold.no-commit", 1),
                {(item.path, item.rule_id, item.line) for item in found},
            )
            (self.root / HOOK_PROPOSAL).unlink()
            found = validation.staged(self.root, policy).findings
        self.assertNotIn(HOOK_PROPOSAL, {item.path for item in found})
