MAX_HOOK_BYTES = 64 * 1024
MISSING_RULE = "hooks.missing"
INVALID_RULE = "hooks.invalid"
GENERATED_MARKER = b"# File generated by pre-commit:"
CONFIG_ARGUMENT = b"--config=.pre-commit-config.yaml"
PYTHON_PREFIX = "INSTALL_PYTHON="


def _within(path: Path, roots: tuple[Path, ...]) -> bool:
    return any(path.is_relative_to(root) for root in roots)


def hook_ready(path: Path, content: bytes, hook_type: str) -> bool:
    if (
        not os.access(path, os.X_OK)
        or GENERATED_MARKER not in content
        or f"--hook-type={hook_type}".encode("ascii") not in content
        or CONFIG_ARGUMENT not in content
    ):
        return False
    try:
        python_line = next(
            (
                line
                for line in content.decode("utf-8").splitlines()
                if line.startswith(PYTHON_PREFIX)
            ),
            "",
        )
        interpreter = shlex.split(python_line.removeprefix(PYTHON_PREFIX))[0]
    except (ValueError, IndexError, UnicodeDecodeError):
        return False
    return os.access(interpreter, os.X_OK)


def _problem(root: Path, hook_type: str, git_roots: tuple[Path, ...]) -> str | None:
    try:
        hook_path = git_path(
            root, run_git(root, ("rev-parse", "--git-path", f"hooks/{hook_type}"))
        )
    except GitError:
        return MISSING_RULE
    # A hooks folder outside the Git metadata is not one Git runs here. The hook
    # itself is not resolved: a symlink there is a hook Git runs, and it is invalid.
    hook_path = hook_path.parent.resolve() / hook_path.name
    if not _within(hook_path.parent, git_roots) or not os.path.lexists(hook_path):
        return MISSING_RULE
    try:
        content = read_regular_bytes(hook_path, MAX_HOOK_BYTES)
    except PathError:
        return INVALID_RULE
    return None if hook_ready(hook_path, content, hook_type) else INVALID_RULE


def hook_problems(root: Path) -> dict[str, str]:
    try:
        git_roots = tuple(
            git_path(root, run_git(root, ("rev-parse", option))).resolve()
            for option in ("--absolute-git-dir", "--git-common-dir")
        )
    except GitError:
        return dict.fromkeys(HOOK_TYPES, MISSING_RULE)
    problems = {
        hook_type: _problem(root, hook_type, git_roots) for hook_type in HOOK_TYPES
    }
    return {hook_type: rule for hook_type, rule in problems.items() if rule}


def hook_findings(root: Path) -> list[Finding]:
    summaries = {
        MISSING_RULE: "Declared Git hook is missing.",
        INVALID_RULE: "Declared Git hook is invalid.",
    }
    return [
        Finding(
            rule_id=rule, path=f"{GIT_HOOKS_PATH}/{hook_type}", summary=summaries[rule]
        )
        for hook_type, rule in hook_problems(root).items()
    ]


def load_hook_config(raw: bytes) -> dict[str, Any]:
    try:
        import yaml
    except ImportError as error:
        raise DependencyError("Setup requires the pre-commit setup extra.") from error

    class UniqueLoader(yaml.SafeLoader):
        pass

    def mapping(loader: yaml.SafeLoader, node: yaml.MappingNode) -> dict[Hashable, Any]:
        value = loader.construct_mapping(node)
        if len(value) != len(node.value) or not all(
            isinstance(key, str) for key in value
        ):
            raise SetupError("Hook configuration has duplicate fields.")
        return value

    UniqueLoader.add_constructor(
        yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, mapping
    )
    try:
        text = raw.decode("utf-8")
        for number, token in enumerate(yaml.scan(text)):
            if number >= MAX_YAML_TOKENS or isinstance(token, yaml.tokens.AliasToken):
                raise SetupError("Hook configuration is too complex or uses aliases.")
        data = yaml.load(text, Loader=UniqueLoader)  # noqa: S506 - UniqueLoader subclasses SafeLoader
    except (UnicodeDecodeError, yaml.YAMLError, RecursionError) as error:
        raise SetupError(MALFORMED) from error
    if not isinstance(data, dict):
        raise SetupError(MALFORMED)
    return data


# The rules below read these fields without guards, so a wrong shape stops here and
# a defect in a rule is never reported as a malformed file.
def hook_entries(data: Mapping[str, Any]) -> list[HookEntry]:
    repositories = data.get("repos")
    if not isinstance(repositories, list):
        raise SetupError(MALFORMED)
    entries: list[HookEntry] = []
    for repository in repositories:
        if not isinstance(repository, dict):
            raise SetupError(MALFORMED)
        hooks = repository.get("hooks")
        if not isinstance(repository.get("repo"), str) or not isinstance(hooks, list):
            raise SetupError(MALFORMED)
        for hook in hooks:
            if not isinstance(hook, dict) or not isinstance(hook.get("id"), str):
                raise SetupError(MALFORMED)
            entries.append((repository, hook))
    return entries


def approved_source(repository: Mapping[str, Any]) -> bool:
    source = repository["repo"]
    return source == "local" or source.removesuffix(".git") in APPROVED_REPOSITORIES


def _runs_only_at(stages: object, stage: str) -> bool:
    return (
        isinstance(stages, list)
        and len(stages) == 1
        and current_stage(stages[0]) == stage
    )


def _local_hook_conflicts(hook: Mapping[str, Any], stage: str) -> bool:
    return bool(
        set(hook) - LOCAL_HOOK_FIELDS
        or hook.get("entry")
        not in (f"first-commit hook {stage}", f"bin/first-commit hook {stage}")
        or hook.get("language") != "system"
        or hook.get("always_run") is not True
        or hook.get("pass_filenames") is not (stage == "commit-msg")
        or not _runs_only_at(hook.get("stages"), stage)
    )


# Callers check the hook's source first; only setup also compares its rev.
def declaration_conflicts(
    repository: Mapping[str, Any], hook: Mapping[str, Any]
) -> bool:
    stage = next(key for key, value in HOOK_IDS.items() if value == hook["id"])
    if repository["repo"] == "local":
        return _local_hook_conflicts(hook, stage)
    return bool(set(hook) - {"id", "stages"}) or (
        "stages" in hook and not _runs_only_at(hook["stages"], stage)
    )


def installed_revision() -> str | None:
    try:
        raw = importlib.metadata.distribution("first-commit").read_text(
            "direct_url.json"
        )
        data = json.loads(raw or "{}")
        found = data.get("vcs_info", {}).get("commit_id")
        url = data.get("url")
    except (
        importlib.metadata.PackageNotFoundError,
        ValueError,
        TypeError,
        AttributeError,
    ):
        return None
    source = url.removesuffix(".git") if isinstance(url, str) else None
    if source not in APPROVED_REPOSITORIES or not isinstance(found, str):
        return None
    return found if REVISION.fullmatch(found) else None


# The shipped manifest runs this id at pre-push when nothing overrides it.
def _is_shipped_push_hook(
    repository: Mapping[str, Any], hook: Mapping[str, Any]
) -> bool:
    return (
        hook["id"] == HOOK_IDS["pre-push"]
        and repository["repo"].removesuffix(".git") in APPROVED_REPOSITORIES
        and set(hook) <= {"id", "stages"}
        and ("stages" not in hook or lists_pre_push(hook))
    )


def _missing_push_rule(entries: list[HookEntry]) -> str | None:
    if any(runs_push_check(hook) for _, hook in entries):
        return None
    pinned = [
        repository.get("rev")
        for repository, hook in entries
        if _is_shipped_push_hook(repository, hook)
    ]
    if not pinned:
        return PUSH_CHECK_RULE
    installed = installed_revision()
    return None if installed is None or installed in pinned else PUSH_REVISION_RULE


# Doctor leaves out the rev that setup compares: a hook pinned to another commit
# still runs that commit's checks.
def _undeclared_rules(entries: list[HookEntry]) -> list[str]:
    rules = []
    for identifier, rule in DECLARATION_RULES.items():
        declared = [entry for entry in entries if entry[1]["id"] == identifier]
        if (
            len(declared) != 1
            or not approved_source(declared[0][0])
            or declaration_conflicts(*declared[0])
        ):
            rules.append(rule)
    return rules


def push_check_findings(root: Path) -> list[Finding]:
    return _hook_file_findings(root) + nested_remote_findings(root)


# No hook file, or no PyYAML to read it (a hook environment), gives no warning.
def _hook_file_findings(root: Path) -> list[Finding]:
    path = root / HOOK_CONFIG
    if not os.path.lexists(path):
        return []
    try:
        entries = hook_entries(
            load_hook_config(read_regular_bytes(path, MAX_HOOK_CONFIG_BYTES))
        )
    except DependencyError:
        return []
    except (PathError, SetupError):
        rules = [*DECLARATION_RULES.values(), PUSH_CHECK_RULE]
    else:
        push_rule = _missing_push_rule(entries)
        rules = _undeclared_rules(entries) + ([push_rule] if push_rule else [])
    return [
        Finding(
            rule_id=rule,
            path=HOOK_CONFIG,
            summary=HOOK_FILE_SUMMARIES[rule],
            severity=Severity.WARNING,
        )
        for rule in rules
    ]
