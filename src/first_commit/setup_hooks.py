TAG = re.compile(r"v[0-9]+(?:\.[0-9]+){0,2}")
# A project may run the push checks from its own pre-push hook instead, when that
# hook runs exactly PUSH_CHECK_COMMAND on every push. A wrapper script does not
# count: setup cannot see what it runs. `check` does not count: it only warns about
# a commit another remote has, so the push could pass.
REQUIRED_HOOK_IDS = (HOOK_IDS["pre-commit"], HOOK_IDS["commit-msg"])
# The marker blocks commits while the proposal or a merged copy of it exists.
PROPOSAL_HEADER = (
    "# @no-commit\n"
    "# Generated by first-commit setup. Merge the first-commit entry under repos:\n"
    f"# and the hook types under default_install_hook_types: into {HOOK_CONFIG},\n"
    "# then delete this file and rerun setup.\n"
)


def hook_bytes(revision: str, source: str = HTTPS_REPOSITORY) -> bytes:
    lines = [
        'minimum_pre_commit_version: "3.2.0"\n',
        "default_install_hook_types:\n",
        *(f"  - {stage}\n" for stage in HOOK_TYPES),
        "repos:\n",
        f"  - repo: {json.dumps(source)}\n",
        f"    rev: {json.dumps(revision)}\n",
        "    hooks:\n",
        *(f"      - id: {HOOK_IDS[stage]}\n" for stage in HOOK_TYPES),
        *(
            f"      - id: {name}\n"
            for name in (SETUP_HOOK_ID, DOCTOR_HOOK_ID, CHECK_HOOK_ID)
        ),
    ]
    return "".join(lines).encode("utf-8")


class HooksMissingError(SetupError):
    def __init__(self, missing: tuple[str, ...]) -> None:
        self.missing = missing
        # Setup sets it to the hook file to merge when the revision is known.
        self.proposal: bytes | None = None
        super().__init__(
            f"{HOOK_CONFIG} does not declare the first-commit hooks "
            + ", ".join(missing)
            + "."
        )


def _source_error() -> SetupError:
    return SetupError(
        f"The first-commit hook source conflicts: {HOOK_CONFIG} takes the hooks from an "
        f"address that is not approved; set repo to {HTTPS_REPOSITORY} or "
        f"{SSH_REPOSITORY}."
    )


# Only a SHA or a version tag is echoed; any other declared value is not shown.
def _revision_error(declared: object, revision: str | None) -> SetupError:
    if not isinstance(declared, str) or not REVISION.fullmatch(declared):
        shown = (
            declared
            if isinstance(declared, str) and TAG.fullmatch(declared)
            else "a value"
        )
        return SetupError(
            f"{HOOK_CONFIG} sets the first-commit rev to {shown}, which is not a "
            f"{REVISION_CHARS}-character commit SHA; a tag can move, so setup accepts "
            "only the commit. Run `pre-commit autoupdate --freeze`, or set rev to the "
            "tag's commit SHA."
        )
    return SetupError(
        f"The first-commit hook revision conflicts: {HOOK_CONFIG} sets rev to "
        f"{declared}, but this first-commit is {revision}; set rev to {revision}, or "
        f"install first-commit at {declared}."
    )


def configured_source(root: Path) -> tuple[str, str]:
    missing = SetupError(
        f"This clone's {HOOK_CONFIG} declares no first-commit hooks at a fixed "
        "revision; restore it from the repository, then retry."
    )
    raw = read_if_present(root / HOOK_CONFIG)
    if raw is None:
        raise missing
    for repository, hook in hook_entries(load_hook_config(raw)):
        if repository["repo"] == "local" or hook["id"] not in HOOK_IDS.values():
            continue
        if not approved_source(repository):
            raise _source_error()
        revision = repository.get("rev")
        if not isinstance(revision, str) or not REVISION.fullmatch(revision):
            raise _revision_error(revision, None)
        return revision, repository["repo"].removesuffix(".git")
    raise missing


def _check_first_commit_hook(
    repository: Mapping[str, Any],
    hook: Mapping[str, Any],
    revision: str | None,
    found: set[str],
) -> None:
    if not approved_source(repository):
        raise _source_error()
    if repository["repo"] != "local" and repository.get("rev") != revision:
        raise _revision_error(repository.get("rev"), revision)
    if hook["id"] in found or declaration_conflicts(repository, hook):
        raise SetupError("The first-commit hook declaration conflicts.")
    found.add(hook["id"])


def _check_declared_hooks(entries: list[HookEntry], revision: str | None) -> None:
    found: set[str] = set()
    push_check = False
    for repository, hook in entries:
        push_check = push_check or runs_push_check(hook)
        if hook["id"] in HOOK_IDS.values():
            _check_first_commit_hook(repository, hook, revision, found)
    required = (
        *REQUIRED_HOOK_IDS,
        *(() if push_check else (HOOK_IDS["pre-push"],)),
    )
    missing = tuple(name for name in required if name not in found)
    if missing:
        raise HooksMissingError(missing)


def check_hook_config(raw: bytes, revision: str | None) -> None:
    data = load_hook_config(raw)
    _check_declared_hooks(hook_entries(data), revision)
    # YAML values such as dates have no JSON form.
    try:
        encoded = json.dumps(data).encode("utf-8")
    except (TypeError, RecursionError) as error:
        raise SetupError(MALFORMED) from error
    validate_schema(encoded)
